const fs = require('fs');
const path = require('path');

const resourcesDir = path.join(__dirname, '../public/assets/Resources');
const outputFile = path.join(__dirname, '../src/app/core/data/generated-resources.ts');

function getHumanReadableSize(bytes) {
  if (bytes === 0) return '0 Bytes';
  const k = 1024;
  const sizes = ['Bytes', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(1)) + ' ' + sizes[i];
}

function cleanTitle(folderName, fileNameWithoutExt) {
  // Specialize Abacus levels
  if (folderName.toLowerCase() === 'abacus' && /^level\d+$/i.test(fileNameWithoutExt)) {
    const num = fileNameWithoutExt.match(/\d+/)[0];
    return `Abacus Level ${num} Workbook`;
  }
  // Specialize known Urdu science book
  if (fileNameWithoutExt === 'میرا خوبصورت جسم - خدا کا تحفہ') {
    return 'میرا خوبصورت جسم - خدا کا تحفہ (Urdu)';
  }
  return fileNameWithoutExt;
}

function generateResources() {
  if (!fs.existsSync(resourcesDir)) {
    console.warn(`Resources directory not found at: ${resourcesDir}. Creating it...`);
    fs.mkdirSync(resourcesDir, { recursive: true });
  }

  const topicResources = {};
  const folders = fs.readdirSync(resourcesDir);

  for (const folder of folders) {
    const folderPath = path.join(resourcesDir, folder);
    if (!fs.statSync(folderPath).isDirectory()) continue;

    const topicKey = folder.toLowerCase();
    topicResources[topicKey] = [];

    const files = fs.readdirSync(folderPath);
    for (const file of files) {
      if (file.startsWith('.')) continue; // ignore hidden files/DS_Store

      const filePath = path.join(folderPath, file);
      const stat = fs.statSync(filePath);
      if (stat.isDirectory()) continue;

      const ext = path.extname(file).toLowerCase();
      const nameWithoutExt = path.basename(file, ext);

      if (ext === '.pdf') {
        const sizeStr = getHumanReadableSize(stat.size);
        const titleStr = cleanTitle(folder, nameWithoutExt);
        // Path needs to match website URL structure (e.g. assets/Resources/Python/file.pdf)
        const webPath = `assets/Resources/${folder}/${file}`;

        topicResources[topicKey].push({
          title: titleStr,
          file: file,
          size: sizeStr,
          path: webPath
        });
      } else if (ext === '.txt' || ext === '.url') {
        // External link/Web app
        const urlContent = fs.readFileSync(filePath, 'utf8').trim();
        if (urlContent) {
          const titleStr = cleanTitle(folder, nameWithoutExt);
          topicResources[topicKey].push({
            title: titleStr,
            file: nameWithoutExt,
            size: 'Web App',
            path: urlContent
          });
        }
      }
    }
  }

  // Format TypeScript content
  const tsContent = `// Automatically generated by scripts/generate-resources.js
// Do not edit this file directly.

export interface GeneratedTopicResource {
  title: string;
  file: string;
  size: string;
  path: string;
}

export const TOPIC_RESOURCES: Record<string, GeneratedTopicResource[]> = ${JSON.stringify(topicResources, null, 2)};
`;

  // Ensure output directory exists
  const outputDir = path.dirname(outputFile);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(outputFile, tsContent, 'utf8');
  console.log(`Successfully generated resources file at: ${outputFile}`);
}

generateResources();
